package com.example.creditworthinesschecker.enums;

public enum CreditRegisterExtractPurpose {
    //New consumer credit contract
    NewConsumerCredit,
    //Increase of consumer credit principal or credit limit
    IncreaseOfConsumerCreditPrincipalOrCreditLimit,
    //Change to terms of consumer credit
    ChangesToTermsOfConsumerCredit,
    //Guarantee or third-party security for consumer credit
    GuaranteeOrThirdPartyPledgeForConsumerCredit,
    //New loan contract for a person other than a consumer
    NewLoan,
    //Increase of the loan principal or credit limit of a loan granted to a person other than a consumer
    IncreaseOfLoanPrincipalOrCreditLimit,
    //Change to the terms of a loan granted to a person other than a consumer
    ChangesToTerms,
    //Guarantee or third-party security for a loan granted to a person other than a consumer
    GuaranteeOrThirdPartyPledge
}
